CREATE TABLE public.routerly_state (
  kind text NOT NULL,
  key text NOT NULL DEFAULT '',
  seq bigint GENERATED BY DEFAULT AS IDENTITY,
  payload jsonb NOT NULL,
  event_timestamp timestamptz,
  byte_size integer NOT NULL DEFAULT 0,
  CONSTRAINT routerly_state_pkey PRIMARY KEY (kind, key, seq),
  CONSTRAINT routerly_state_kind_check CHECK (kind IN ('config', 'usage')),
  CONSTRAINT routerly_state_shape_check CHECK (
    (kind = 'config' AND key <> '' AND seq = 0 AND event_timestamp IS NULL AND byte_size = 0)
    OR (kind = 'usage' AND key = '' AND seq > 0 AND byte_size >= 0)
  )
);
